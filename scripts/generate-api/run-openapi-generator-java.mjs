// Emits the Java DTOs for the Android binding, from the same OpenAPI document
// the C# models come from.
//
// Gson, not Jackson: Jackson is far too heavy for an APK, and Gson is the one
// mainstream option openapi-generator supports that works on API 21. It is a
// dependency the consuming app gains — Telegram Android ships neither today, and
// only the platform's org.json — so if that is unacceptable the alternative is
// custom templates emitting org.json parsing, which is a bigger commitment than
// it sounds. Documented in docs/BINDINGS.md.
//
// Models only. The rest of the generator's output is an HTTP client we do not
// use, because the transport is the C ABI.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const VERSION = '7.9.0';
const jar = path.resolve('build', `openapi-generator-cli-${VERSION}.jar`);
const out = path.resolve('../../bindings/android/src/main/java/org/ton/walletkit/api');

if (!fs.existsSync(jar)) {
    console.error(`missing ${jar} — run \`npm run csharp\` first, which downloads it`);
    process.exit(1);
}

// Both staging and destination are wiped: the generator leaves files for models
// that no longer exist, and a stale one would compile against nothing.
fs.rmSync(path.resolve('build/java'), { recursive: true, force: true });
fs.rmSync(out, { recursive: true, force: true });

execFileSync('java', [
    '-jar', jar, 'generate',
    '-i', 'build/openapi.json',
    '--skip-validate-spec',
    '-g', 'java',
    '--library', 'okhttp-gson',
    '-o', 'build/java',
    '--global-property', 'models',
    '--additional-properties',
    [
        'serializationLibrary=gson',
        'modelPackage=org.ton.walletkit.api',
        'invokerPackage=org.ton.walletkit.api',
        'modelNamePrefix=TON',
        'hideGenerationTimestamp=true',
        'openApiNullable=false',
        // Android 21: java.time is not there, and this only affects unused fields.
        'dateLibrary=legacy',
        'useBeanValidation=false',
        'performBeanValidation=false',
        'disallowAdditionalPropertiesIfNotPresent=false',
    ].join(','),
], { stdio: 'inherit' });

const src = path.resolve('build/java/src/main/java/org/ton/walletkit/api');
fs.mkdirSync(out, { recursive: true });

// The generator decorates everything with JSR-305 (javax.annotation), which
// Android does not ship and which would mean another dependency for nothing:
// the annotations are compile-time only. Stripped on the way out rather than by
// making the consuming app carry a jar for them.
const IMPORT = /^import javax[.]annotation[.]/;
const GENERATED = /^@javax[.]annotation[.]Generated/;
const INLINE = /@(javax[.]annotation[.])?(Nullable|Nonnull)\s*/g;

function stripAnnotations(source) {
    const kept = source.split(/\r?\n/).filter((line) => !IMPORT.test(line) && !GENERATED.test(line));
    return kept.join('\n').replace(INLINE, '');
}

let copied = 0;
for (const file of fs.readdirSync(src)) {
    if (!file.endsWith('.java')) continue;
    fs.writeFileSync(path.join(out, file), stripAnnotations(fs.readFileSync(path.join(src, file), 'utf8')));
    copied++;
}

// walletkit's unions (SignData, RawStackItem, …) generate as anyOf models that
// extend AbstractOpenApiSchema, which likewise only ships with the full client.
fs.writeFileSync(path.join(out, 'AbstractOpenApiSchema.java'), `/*
 * GENERATED by scripts/generate-api/run-openapi-generator-java.mjs — do not edit.
 */
package org.ton.walletkit.api;

import java.util.Map;

/** Base for the anyOf/oneOf models: one of several shapes, decided at runtime. */
public abstract class AbstractOpenApiSchema {

    private Object instance;
    private final Boolean isNullable;
    private final String schemaType;

    public AbstractOpenApiSchema(String schemaType, Boolean isNullable) {
        this.schemaType = schemaType;
        this.isNullable = isNullable;
    }

    /** The variants this schema accepts, by name. */
    public abstract Map<String, Class<?>> getSchemas();

    /** Whichever variant was actually present. */
    public Object getActualInstance() {
        return instance;
    }

    public void setActualInstance(Object instance) {
        this.instance = instance;
    }

    public Boolean isNullable() {
        return isNullable;
    }

    public String getSchemaType() {
        return schemaType;
    }

    @Override
    public String toString() {
        return String.valueOf(instance);
    }
}
`);

// The models' fromJson/toJson helpers call JSON.getGson(). That class only comes
// with the full generated client, which drags in gson-fire and okhttp for an
// HTTP stack we do not use — the transport is the C ABI. Fifteen lines here
// instead of two dependencies in the APK.
fs.writeFileSync(path.join(out, 'JSON.java'), `/*
 * GENERATED by scripts/generate-api/run-openapi-generator-java.mjs — do not edit.
 */
package org.ton.walletkit.api;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;

/** The Gson instance the generated models serialize themselves with. */
public class JSON {

    private static final Gson GSON = new GsonBuilder().disableHtmlEscaping().create();

    public static Gson getGson() {
        return GSON;
    }

    public static String serialize(Object value) {
        return GSON.toJson(value);
    }

    public static <T> T deserialize(String json, Class<T> type) {
        return GSON.fromJson(json, type);
    }
}
`);

console.log(`generated ${copied} Java models -> ${path.relative(process.cwd(), out)}`);
