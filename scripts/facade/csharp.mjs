// Emits the C# facade from api/facade.json.
//
// What is generated: the interfaces, the wallet/adapter/signer implementations,
// the mechanical kit methods, and the TON Connect request objects. What is not:
// the transport, the delegates, the configuration and the descriptors — all
// hand-written, all listed in docs/BINDINGS.md.
//
// Methods marked `custom` in the schema are declared here and implemented by hand
// in the matching partial class, so the API stays uniform even where the body is
// not mechanical.

const HEADER = (what) => `//
// ${what}
//
// GENERATED by scripts/generate-facade.mjs from api/facade.json — do not edit.
// Change the schema, then regenerate.
//
`;

// ---- naming ---------------------------------------------------------------

const pascal = (name) => name.charAt(0).toUpperCase() + name.slice(1);
const camel = (name) => name.charAt(0).toLowerCase() + name.slice(1);

/** The C# type name for a facade object. */
const objectType = (name) => (name === 'Kit' ? 'TonWalletKit' : `Ton${name === 'Signer' ? 'WalletSigner' : name === 'Adapter' ? 'WalletAdapter' : name}`);
const interfaceType = (name) => `I${objectType(name)}`;

const methodName = (method) => `${pascal(method.name)}Async`;

// ---- types ----------------------------------------------------------------

const SIMPLE = {
    string: 'string',
    bool: 'bool',
    int: 'int',
    bytes: 'byte[]',
    amount: 'TonAmount',
    mnemonic: 'TonMnemonic',
    feature: 'TonFeature',
    chainId: 'string',
    creationResult: 'TonWalletCreationResult',
    fakeSignature: 'bool?',
};

function typeName(type, { arg = false } = {}) {
    if (SIMPLE[type]) return SIMPLE[type];
    if (type.startsWith('dto:')) return type.slice(4);
    if (type.startsWith('object:')) return interfaceType(type.slice(7));
    if (type.startsWith('params:')) return `Ton${type.slice(7)}WalletParameters`;

    const list = /^list<(.+)>$/.exec(type);
    if (list) {
        const inner = typeName(list[1]);
        return arg ? `IEnumerable<${inner}>` : `IReadOnlyList<${inner}>`;
    }

    throw new Error(`unmapped type: ${type}`);
}

function returnType(type) {
    if (type === 'void') return 'Task';
    return `Task<${typeName(type)}>`;
}

// ---- docs -----------------------------------------------------------------

const lines = (doc) => (Array.isArray(doc) ? doc : [doc]);

function docComment(doc, indent, remarks) {
    if (!doc) return '';
    const pad = ' '.repeat(indent);
    const body = lines(doc);
    let out = body.length === 1
        ? `${pad}/// <summary>${body[0]}</summary>\n`
        : `${pad}/// <summary>\n${body.map((line) => `${pad}/// ${line}`).join('\n')}\n${pad}/// </summary>\n`;
    if (remarks) {
        out += `${pad}/// <remarks>\n${lines(remarks).map((line) => `${pad}/// ${line}`).join('\n')}\n${pad}/// </remarks>\n`;
    }
    return out;
}

// ---- signatures -----------------------------------------------------------

function parameters(method) {
    return method.args
        .filter((arg) => arg.constant === undefined)
        .map((arg) => {
            const type = typeName(arg.type, { arg: true });
            if (arg.default !== undefined) return `${type} ${camel(arg.name)} = ${arg.default}`;
            if (arg.optional) return `${type} ${camel(arg.name)} = null`;
            return `${type} ${camel(arg.name)}`;
        })
        .join(', ');
}

const signature = (method) => `${returnType(method.returns)} ${methodName(method)}(${parameters(method)})`;

// ---- call bodies ----------------------------------------------------------

/** How one argument is written into the ABI's positional array. */
function argument(arg, { raw }) {
    const name = camel(arg.name);

    if (arg.constant !== undefined) {
        return raw ? `TonJson.Serialize("${arg.constant}")` : `"${arg.constant}"`;
    }
    if (arg.type.startsWith('params:')) {
        return `${name}.ToJson()`; // already JSON: only valid in raw mode
    }
    if (arg.type === 'mnemonic') {
        const expr = `new List<string>(${name}.Value)`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    if (arg.type === 'chainId') {
        const expr = `ChainId(${name})`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    if (arg.type === 'fakeSignature') {
        const expr = `Options(${name})`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    if (arg.type === 'object:Signer') {
        const expr = `SignerId(${name}, nameof(${name}))`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    if (arg.type.startsWith('object:')) {
        const expr = `Handle(${name}, nameof(${name}))`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    if (/^list<dto:/.test(arg.type)) {
        const inner = typeName(/^list<(.+)>$/.exec(arg.type)[1]);
        const expr = `new List<${inner}>(${name})`;
        return raw ? `TonJson.Serialize(${expr})` : expr;
    }
    return raw ? `TonJson.Serialize(${name})` : name;
}

/** The `TonJson.Args(…)` expression for a call, including the object handle. */
function argsExpression(method, handle) {
    // Wallet parameters write themselves, so any call carrying one has to build
    // its argument array from JSON fragments rather than from values.
    const raw = method.args.some((arg) => arg.type.startsWith('params:'));
    const parts = [];
    if (handle) parts.push(raw ? `TonJson.Serialize(${handle})` : handle);
    for (const arg of method.args) parts.push(argument(arg, { raw }));

    if (parts.length === 0) return 'TonJson.Args()';
    return `${raw ? 'TonJson.ArgsRaw' : 'TonJson.Args'}(${parts.join(', ')})`;
}

/** The body of a mechanical method. */
function body(method, { invoke, handle, indent }) {
    const pad = ' '.repeat(indent);
    const args = argsExpression(method, handle);
    // `this.` would be noise on the kit's own methods.
    const self = invoke === 'this' ? '' : `${invoke}.`;
    const call = (type) => `${self}InvokeAsync<${type}>("${method.abi}", ${args})`;
    const wrap = (text) => text.split('\n').map((line) => (line ? pad + line : line)).join('\n') + '\n';

    if (method.returns === 'void') {
        return wrap(`return ${self}CallAsync("${method.abi}", ${args});`);
    }

    if (method.returns === 'amount') {
        return wrap(`string value = await ${call('string')}.ConfigureAwait(false);\n` +
                    `return TonAmount.FromNanotons(value);`);
    }

    if (method.returns === 'mnemonic') {
        return wrap(`var words = await ${call('List<string>')}.ConfigureAwait(false);\n` +
                    `return new TonMnemonic(words ?? new List<string>());`);
    }

    const object = /^object:(.+)$/.exec(method.returns);
    if (object) {
        const schemaObject = object[1];
        return wrap(`var descriptor = await ${call(descriptorOf(schemaObject))}.ConfigureAwait(false);\n` +
                    `return descriptor == null ? null : new ${objectType(schemaObject)}(this, descriptor);`);
    }

    const list = /^list<(.+)>$/.exec(method.returns);
    if (list) {
        const innerObject = /^object:(.+)$/.exec(list[1]);
        if (innerObject) {
            const schemaObject = innerObject[1];
            const type = objectType(schemaObject);
            return wrap(
                `var descriptors = await ${call(`List<${descriptorOf(schemaObject)}>`)}.ConfigureAwait(false);\n` +
                `var items = new List<${interfaceType(schemaObject)}>(descriptors == null ? 0 : descriptors.Count);\n` +
                `if (descriptors != null)\n{\n    foreach (var descriptor in descriptors)\n` +
                `    {\n        items.Add(new ${type}(this, descriptor));\n    }\n}\n` +
                `return items;`);
        }

        const inner = typeName(list[1]);
        return wrap(`var items = await ${call(`List<${inner}>`)}.ConfigureAwait(false);\n` +
                    `return items ?? (IReadOnlyList<${inner}>)new ${inner}[0];`);
    }

    return wrap(`return ${call(typeName(method.returns))};`);
}

const descriptorOf = (name) => ({ Signer: 'TonSignerDescriptor', Adapter: 'TonAdapterDescriptor', Wallet: 'TonWalletDescriptor' })[name];

/**
 * How a return value is read back. Only the shapes that unwrap something await,
 * so the rest stay plain Task-returning methods with no state machine.
 */
function returnKind(returns) {
    if (returns === 'void') return 'call';
    if (returns === 'amount') return 'amount';
    if (returns === 'mnemonic') return 'mnemonic';
    if (/^object:/.test(returns)) return 'object';
    if (/^list<object:/.test(returns)) return 'objectList';
    if (/^list</.test(returns)) return 'list';
    return 'invoke';
}

const isAsync = (method) => !['call', 'invoke'].includes(returnKind(method.returns));

function method(m, { invoke, handle, indent }) {
    const pad = ' '.repeat(indent);
    let out = docComment(m.doc, indent, m.remarks);
    out += `${pad}public ${isAsync(m) ? 'async ' : ''}${signature(m)}\n${pad}{\n`;
    out += body(m, { invoke, handle, indent: indent + 4 });
    out += `${pad}}\n`;
    return out;
}

// ---- files ----------------------------------------------------------------

function interfaces(schema) {
    let out = HEADER('The wallet object model, mirroring kit-ios method for method.');
    out += `using System.Collections.Generic;\nusing System.Threading.Tasks;\nusing Ton.WalletKit.Api.Model;\n\n`;
    out += `namespace Ton.WalletKit\n{\n`;

    for (const object of schema.objects.filter((o) => !o.root)) {
        out += docComment(object.doc, 4);
        const base = object.extends ? ` : ${interfaceType(object.extends)}` : '';
        out += `    public interface ${interfaceType(object.name)}${base}\n    {\n`;

        const members = [];
        for (const property of object.properties ?? []) {
            members.push(docComment(property.doc, 8) + `        ${typeName(property.type)} ${pascal(property.name)} { get; }\n`);
        }
        for (const m of object.methods) {
            members.push(docComment(m.doc, 8, m.remarks) + `        ${signature(m)};\n`);
        }
        out += members.join('\n');
        out += `    }\n\n`;
    }

    return out.trimEnd() + '\n}\n';
}

function implementations(schema) {
    let out = HEADER('The wallet objects the kit hands out: an id, plus what kit-ios exposes synchronously.');
    out += `using System.Collections.Generic;\nusing System.Threading.Tasks;\nusing Ton.WalletKit.Api.Model;\n\n`;
    out += `namespace Ton.WalletKit\n{\n`;

    for (const object of schema.objects.filter((o) => !o.root)) {
        const type = objectType(object.name);
        const base = object.extends ? objectType(object.extends) : null;
        const inherited = schema.objects.some((o) => o.extends === object.name);
        const sealedOrNot = inherited ? '' : 'sealed ';

        out += docComment(object.doc, 4);
        const bases = [base, interfaceType(object.name)].filter(Boolean).join(', ');
        out += `    internal ${sealedOrNot}class ${type} : ${bases}\n    {\n`;

        // Every object is addressed by an id, and carries the properties the
        // descriptor reported when it was created.
        if (!base) {
            // protected only where something actually derives from this: the
            // compiler warns about a protected member on a sealed class, since
            // nothing can ever reach it.
            out += `        /// <summary>The kit this object belongs to.</summary>\n`;
            out += `        ${inherited ? 'protected' : 'private'} TonWalletKit Kit { get; }\n\n`;
            out += `        /// <summary>The id the ABI addresses this object by.</summary>\n`;
            out += `        internal string Handle { get; }\n\n`;
        }

        const own = object.properties ?? [];
        for (const property of own) {
            out += `        /// <inheritdoc/>\n        public ${typeName(property.type)} ${pascal(property.name)} { get; }\n\n`;
        }

        // Constructor: from this object's own descriptor, and — for a wallet —
        // also from the adapter it was registered from.
        out += constructor(object, schema);

        for (const m of object.methods) {
            out += '\n' + methodImplementation(m, object);
        }

        if (object.methods.some((m) => m.args.some((a) => a.type === 'fakeSignature'))) {
            out += `\n        private static TONSignedSendTransactionOptions Options(bool? fakeSignature)\n        {\n` +
                   `            return fakeSignature.HasValue\n` +
                   `                ? new TONSignedSendTransactionOptions(fakeSignature.Value)\n` +
                   `                : null;\n        }\n`;
        }

        out += `    }\n\n`;
    }

    return out.trimEnd() + '\n}\n';
}

function constructor(object, schema) {
    const type = objectType(object.name);
    const base = object.extends ? objectType(object.extends) : null;

    const assignments = (source) => (object.properties ?? [])
        .map((property) => `            ${pascal(property.name)} = ${source}.${pascal(property.from ?? property.name)};\n`)
        .join('');

    if (base) {
        return `        internal ${type}(TonWalletKit kit, ${descriptorOf(object.name)} descriptor) : base(kit, descriptor)\n` +
               `        {\n${assignments('descriptor')}        }\n`;
    }

    // A base class needs a constructor per descriptor it can be built from: its
    // own, and each subclass's — a registered wallet arrives as one wallet
    // descriptor and has to fill in the adapter half from it too.
    const sources = [object, ...schema.objects.filter((o) => o.extends === object.name)];
    return sources
        .map((source) =>
            `        internal ${type}(TonWalletKit kit, ${descriptorOf(source.name)} descriptor)\n        {\n` +
            `            Kit = kit;\n            Handle = descriptor.${pascal(source.handle)};\n` +
            assignments('descriptor') +
            `        }\n`)
        .join('\n');
}

function methodImplementation(m, object) {
    const invoke = object.root ? 'this' : 'Kit';
    const handle = object.root ? null : (object.name === 'Signer' ? 'Handle' : 'Handle');
    let out = `        /// <inheritdoc/>\n`;
    out += `        public ${isAsync(m) ? 'async ' : ''}${signature(m)}\n        {\n`;
    out += body(m, { invoke, handle, indent: 12 });
    out += `        }\n`;
    return out;
}

function kit(schema) {
    const object = schema.objects.find((o) => o.root);
    let out = HEADER('The typed entry point (kit-ios TONWalletKit): the mechanical half.');
    out += `using System.Collections.Generic;\nusing System.Threading.Tasks;\nusing Ton.WalletKit.Api.Model;\n\n`;
    out += `namespace Ton.WalletKit\n{\n`;
    out += `    public sealed partial class TonWalletKit\n    {\n`;

    const methods = object.methods.filter((m) => !m.custom);
    out += methods.map((m) => method(m, { invoke: 'this', handle: null, indent: 8 })).join('\n');

    out += `    }\n}\n`;
    return out;
}

function events(schema) {
    let out = HEADER('What a dapp asks for, and how the app answers (kit-ios Bridge + Requests).');
    out += `using System;\nusing System.Threading.Tasks;\nusing Ton.WalletKit.Api.Model;\n\n`;
    out += `namespace Ton.WalletKit\n{\n`;

    // The event union.
    const cases = [...schema.requests.map((r) => ({ name: r.name.replace(/Request$/, '') + 'Request', type: r.eventType, doc: r.doc })),
                   { name: 'Disconnect', type: schema.events.disconnect.eventType, doc: schema.events.disconnect.doc }];

    out += `    /// <summary>Which kind of request arrived (kit-ios TONWalletKitEvent cases).</summary>\n`;
    out += `    public enum TonWalletKitEventType\n    {\n`;
    out += cases.map((c) => `        /// <summary>${lines(c.doc)[0]}</summary>\n        ${eventCase(c.type)},\n`).join('\n');
    out += `    }\n\n`;

    out += docComment([lines(schema.events.doc)[0],
                       'Exactly one of the request properties is set, matching Type.'], 4);
    out += `    public sealed class TonWalletKitEvent : EventArgs\n    {\n`;
    out += `        /// <summary>Which kind of event this is.</summary>\n        public TonWalletKitEventType Type { get; }\n\n`;
    for (const request of schema.requests) {
        out += `        /// <summary>Set when Type is ${eventCase(request.eventType)}.</summary>\n`;
        out += `        public ${requestType(request)} ${eventCase(request.eventType)} { get; internal set; }\n\n`;
    }
    out += `        /// <summary>Set when Type is Disconnect.</summary>\n`;
    out += `        public ${schema.events.disconnect.event} Disconnect { get; internal set; }\n\n`;
    out += `        internal TonWalletKitEvent(TonWalletKitEventType type)\n        {\n            Type = type;\n        }\n`;
    out += `    }\n\n`;

    for (const request of schema.requests) {
        out += requestClass(request);
    }

    return out.trimEnd() + '\n}\n';
}

const eventCase = (eventType) => pascal(eventType);

// kit-ios calls these TONWallet…Request; the Wallet keeps them apart from the
// walletkit event DTOs they carry (TONConnectionRequestEvent and friends).
const requestType = (request) => `TonWallet${request.name}`;

function requestClass(request) {
    const type = requestType(request);
    const partial = request.custom ? 'partial ' : '';

    let out = docComment(request.doc, 4);
    out += `    public sealed ${partial}class ${type}\n    {\n`;
    out += `        private readonly TonWalletKit _kit;\n\n`;
    out += `        /// <summary>The request, as the dapp sent it.</summary>\n`;
    out += `        public ${request.event} Event { get; }\n\n`;

    if (request.embedded) {
        out += `        /// <summary>Set when the request came embedded in a connect approval.</summary>\n`;
        out += `        public ${request.embedded} EmbeddedEvent { get; }\n\n`;
    }

    out += `        internal ${type}(TonWalletKit kit, ${request.event} request)\n        {\n`;
    out += `            _kit = kit;\n            Event = request;\n        }\n`;

    if (request.embedded) {
        out += `\n        internal ${type}(TonWalletKit kit, ${request.embedded} embedded)\n        {\n`;
        out += `            _kit = kit;\n            EmbeddedEvent = embedded;\n        }\n`;
    }

    // The answer must carry the event it really came from: the embedded one when
    // the dapp bundled the request into a connect, otherwise the plain one.
    const dispatch = (call) => request.embedded
        ? `            return EmbeddedEvent != null\n                ? ${call('EmbeddedEvent')}\n                : ${call('Event')};\n`
        : `            return ${call('Event')};\n`;

    if (!request.custom) {
        const approve = (event) =>
            `_kit.InvokeAsync<${request.response}>("${request.approve}", TonJson.Args(${event}, response))`;
        out += `\n` + docComment(request.approveDoc, 8);
        out += `        public Task<${request.response}> ApproveAsync(${request.response} response = null)\n        {\n`;
        out += dispatch(approve);
        out += `        }\n`;
    }

    const reject = (event) => `_kit.CallAsync("${request.reject}", TonJson.Args(${event}, reason))`;
    out += `\n` + docComment(request.rejectDoc ?? 'Refuses the request.', 8);
    out += `        public Task RejectAsync(string reason = null)\n        {\n`;
    out += dispatch(reject);
    out += `        }\n`;

    out += `    }\n\n`;
    return out;
}

export function emit(schema) {
    const dir = 'bindings/csharp/src/Facade';
    return [
        { path: `${dir}/ITonWallet.g.cs`, content: interfaces(schema) },
        { path: `${dir}/TonWallet.g.cs`, content: implementations(schema) },
        { path: `${dir}/TonWalletKit.g.cs`, content: kit(schema) },
        { path: `${dir}/TonWalletKitEvent.g.cs`, content: events(schema) },
    ];
}
