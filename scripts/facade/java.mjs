// Emits the Java facade from api/facade.json, for the Android binding.
//
// Same schema as the C# emitter, different conventions: Java 8, callbacks rather
// than futures (CompletableFuture needs API 24 and Telegram Android is 21), and
// interfaces without the I prefix. What is generated is the same three things:
// the object model, its implementations, and the mechanical kit methods.

const HEADER = (what) => `//
// ${what}
//
// GENERATED by scripts/generate-facade.mjs from api/facade.json — do not edit.
// Change the schema, then regenerate.
//
package org.ton.walletkit.core;

import java.util.List;

import org.ton.walletkit.api.*;

`;

const pascal = (name) => name.charAt(0).toUpperCase() + name.slice(1);
const camel = (name) => name.charAt(0).toLowerCase() + name.slice(1);

/** Interfaces carry the plain name; implementations get Impl. */
const interfaceType = (name) => (name === 'Kit' ? 'TonWalletKit' : `Ton${name === 'Adapter' ? 'WalletAdapter' : name === 'Signer' ? 'Signer' : name}`);
const objectType = (name) => `${interfaceType(name)}Impl`;

const descriptorOf = (name) =>
    ({ Signer: 'TonSignerDescriptor', Adapter: 'TonAdapterDescriptor', Wallet: 'TonWalletDescriptor' })[name];

const SIMPLE = {
    string: 'String',
    bool: 'Boolean',
    int: 'Integer',
    bytes: 'byte[]',
    amount: 'TonAmount',
    mnemonic: 'TonMnemonic',
    feature: 'TonFeature',
    chainId: 'String',
    creationResult: 'TonWalletCreationResult',
    fakeSignature: 'Boolean',
};

function typeName(type) {
    if (SIMPLE[type]) return SIMPLE[type];
    if (type.startsWith('dto:')) return type.slice(4);
    if (type.startsWith('object:')) return interfaceType(type.slice(7));
    if (type.startsWith('params:')) return `Ton${type.slice(7)}WalletParameters`;

    const list = /^list<(.+)>$/.exec(type);
    if (list) return `List<${typeName(list[1])}>`;

    throw new Error(`unmapped type: ${type}`);
}

/** The callback's payload type; void becomes Void. */
const callbackType = (returns) => (returns === 'void' ? 'Void' : typeName(returns));

const lines = (doc) => (Array.isArray(doc) ? doc : [doc]);

function javadoc(doc, indent, remarks) {
    if (!doc) return '';
    const pad = ' '.repeat(indent);
    const body = [...lines(doc)];
    if (remarks) {
        body.push('', ...lines(remarks));
    }
    if (body.length === 1) {
        return `${pad}/** ${body[0]} */\n`;
    }
    return `${pad}/**\n${body.map((line) => (line ? `${pad} * ${line}` : `${pad} *`)).join('\n')}\n${pad} */\n`;
}

const methodName = (method) => camel(method.name);

function parameters(method) {
    const own = method.args
        .filter((arg) => arg.constant === undefined)
        .map((arg) => `${typeName(arg.type)} ${camel(arg.name)}`);
    own.push(`Callback<${callbackType(method.returns)}> callback`);
    return own.join(', ');
}

const signature = (method) => `void ${methodName(method)}(${parameters(method)})`;

/** How one argument is written into the positional array. */
function argument(arg) {
    const name = camel(arg.name);
    if (arg.constant !== undefined) return `"${arg.constant}"`;
    if (arg.type.startsWith('params:')) return `${name} == null ? null : ${name}.toJson()`;
    if (arg.type === 'mnemonic') return `${name}.getValue()`;
    if (arg.type === 'chainId') return `chainId(${name})`;
    if (arg.type === 'fakeSignature') return `TonJson.signOptions(${name})`;
    if (arg.type === 'object:Signer') return `handleOf(${name})`;
    if (arg.type.startsWith('object:')) return `handleOf(${name})`;
    return name;
}

function argsExpression(method, handle) {
    const parts = [];
    if (handle) parts.push(handle);
    for (const arg of method.args) parts.push(argument(arg));
    // Wallet parameters serialize themselves, so they go in as raw JSON.
    const raw = method.args.some((arg) => arg.type.startsWith('params:'));
    return `${raw ? 'TonJson.argsRaw' : 'TonJson.args'}(${parts.join(', ')})`;
}

function returnKind(returns) {
    if (returns === 'void') return 'call';
    if (returns === 'amount') return 'amount';
    if (returns === 'mnemonic') return 'mnemonic';
    if (/^object:/.test(returns)) return 'object';
    if (/^list<object:/.test(returns)) return 'objectList';
    if (/^list<(.+)>$/.test(returns)) return 'list';
    return 'invoke';
}

function body(method, { invoke, handle, indent }) {
    const pad = ' '.repeat(indent);
    const args = argsExpression(method, handle);
    const kind = returnKind(method.returns);
    const target = invoke ? `${invoke}.` : '';

    switch (kind) {
        case 'call':
            return `${pad}${target}invokeVoid("${method.abi}", ${args}, callback);\n`;
        case 'amount':
            return `${pad}${target}invokeAmount("${method.abi}", ${args}, callback);\n`;
        case 'mnemonic':
            return `${pad}${target}invokeMnemonic("${method.abi}", ${args}, callback);\n`;
        case 'object': {
            const name = /^object:(.+)$/.exec(method.returns)[1];
            return `${pad}${target}invokeObject("${method.abi}", ${args}, ${descriptorOf(name)}.class,\n` +
                   `${pad}        ${objectType(name)}.FACTORY, callback);\n`;
        }
        case 'objectList': {
            const name = /^list<object:(.+)>$/.exec(method.returns)[1];
            return `${pad}${target}invokeObjectList("${method.abi}", ${args}, ${descriptorOf(name)}[].class,\n` +
                   `${pad}        ${objectType(name)}.FACTORY, callback);\n`;
        }
        case 'list': {
            const inner = typeName(/^list<(.+)>$/.exec(method.returns)[1]);
            return `${pad}${target}invokeList("${method.abi}", ${args}, ${inner}[].class, callback);\n`;
        }
        default:
            return `${pad}${target}invoke("${method.abi}", ${args}, ${typeName(method.returns)}.class, callback);\n`;
    }
}

// ---- files ----------------------------------------------------------------

function interfaces(schema) {
    const files = [];
    for (const object of schema.objects.filter((o) => !o.root)) {
        let out = HEADER(`${interfaceType(object.name)} — part of the wallet object model.`);
        out += javadoc(object.doc, 0);
        const extend = object.extends ? ` extends ${interfaceType(object.extends)}` : '';
        out += `public interface ${interfaceType(object.name)}${extend} {\n\n`;

        for (const property of object.properties ?? []) {
            out += javadoc(property.doc, 4);
            out += `    ${typeName(property.type)} get${pascal(property.name)}();\n\n`;
        }
        for (const method of object.methods) {
            out += javadoc(method.doc, 4, method.remarks);
            out += `    ${signature(method)};\n\n`;
        }

        out += `}\n`;
        files.push({ name: `${interfaceType(object.name)}.java`, content: out });
    }
    return files;
}

function implementations(schema) {
    const files = [];
    for (const object of schema.objects.filter((o) => !o.root)) {
        const type = objectType(object.name);
        const base = object.extends ? objectType(object.extends) : null;

        let out = HEADER(`${type} — a handle: an id, plus what the descriptor reported.`);
        out += `class ${type}${base ? ` extends ${base}` : ''} implements ${interfaceType(object.name)} {\n\n`;

        if (!base) {
            out += `    final TonWalletKit kit;\n`;
            out += `    /** The id the ABI addresses this object by. */\n    final String handle;\n\n`;
        }

        for (const property of object.properties ?? []) {
            out += `    private final ${typeName(property.type)} ${camel(property.name)};\n`;
        }
        out += '\n';

        // One constructor per descriptor this class can be built from — a wallet
        // arrives as one descriptor and fills in the adapter half from it too.
        const sources = base ? [object] : [object, ...schema.objects.filter((o) => o.extends === object.name)];
        for (const source of sources) {
            const descriptor = descriptorOf(source.name);
            out += `    ${type}(TonWalletKit kit, ${descriptor} descriptor) {\n`;
            if (base) {
                out += `        super(kit, descriptor);\n`;
            } else {
                out += `        this.kit = kit;\n        this.handle = descriptor.${camel(source.handle)};\n`;
            }
            for (const property of object.properties ?? []) {
                out += `        this.${camel(property.name)} = descriptor.${camel(property.from ?? property.name)};\n`;
            }
            out += `    }\n\n`;
        }

        // The factory the invoker uses to turn a descriptor into an object.
        const own = descriptorOf(object.name);
        out += `    static final TonWalletKit.Factory<${own}, ${interfaceType(object.name)}> FACTORY =\n`;
        out += `            new TonWalletKit.Factory<${own}, ${interfaceType(object.name)}>() {\n`;
        out += `                @Override\n`;
        out += `                public ${interfaceType(object.name)} create(TonWalletKit kit, ${own} descriptor) {\n`;
        out += `                    return new ${type}(kit, descriptor);\n`;
        out += `                }\n            };\n\n`;

        for (const property of object.properties ?? []) {
            out += `    @Override\n    public ${typeName(property.type)} get${pascal(property.name)}() {\n`;
            out += `        return ${camel(property.name)};\n    }\n\n`;
        }

        for (const method of object.methods) {
            out += `    @Override\n    public ${signature(method)} {\n`;
            out += body(method, { invoke: 'kit', handle: 'handle', indent: 8 });
            out += `    }\n\n`;
        }

        out += `}\n`;
        files.push({ name: `${type}.java`, content: out });
    }
    return files;
}

function kit(schema) {
    const object = schema.objects.find((o) => o.root);
    let out = HEADER('The mechanical half of the kit; the rest is in TonWalletKit.java.');
    out += `abstract class TonWalletKitGenerated {\n\n`;

    // The invoker methods the generated bodies call, implemented by TonWalletKit.
    out += `    abstract void invoke(String method, String args, Class<?> type, Callback<?> callback);\n\n`;
    out += `    abstract void invokeVoid(String method, String args, Callback<Void> callback);\n\n`;
    out += `    abstract void invokeAmount(String method, String args, Callback<TonAmount> callback);\n\n`;
    out += `    abstract void invokeMnemonic(String method, String args, Callback<TonMnemonic> callback);\n\n`;
    out += `    abstract void invokeList(String method, String args, Class<?> arrayType, Callback<?> callback);\n\n`;
    out += `    abstract <D, T> void invokeObject(String method, String args, Class<D> descriptor,\n`;
    out += `                                      TonWalletKit.Factory<D, T> factory, Callback<T> callback);\n\n`;
    out += `    abstract <D, T> void invokeObjectList(String method, String args, Class<D[]> descriptors,\n`;
    out += `                                          TonWalletKit.Factory<D, T> factory,\n`;
    out += `                                          Callback<List<T>> callback);\n\n`;
    out += `    abstract String chainId(String chainId);\n\n`;
    out += `    abstract String handleOf(Object object);\n\n`;

    for (const method of object.methods.filter((m) => !m.custom)) {
        out += javadoc(method.doc, 4, method.remarks);
        out += `    public ${signature(method)} {\n`;
        out += body(method, { invoke: '', handle: null, indent: 8 });
        out += `    }\n\n`;
    }

    out += `}\n`;
    return [{ name: 'TonWalletKitGenerated.java', content: out }];
}

export function emit(schema) {
    // Same package as the hand-written runtime: Java ties packages to
    // directories, so a subpackage would mean importing everything back.
    const dir = 'bindings/android/src/main/java/org/ton/walletkit/core';
    return [...interfaces(schema), ...implementations(schema), ...kit(schema)].map((file) => ({
        path: `${dir}/${file.name}`,
        content: file.content,
    }));
}
