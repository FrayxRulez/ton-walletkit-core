// Regenerates THIRD_PARTY_NOTICES.md.
//
//   node scripts/generate-notices.mjs
//
// twk.dll does not merely depend on this code — it *contains* it: the JS bundle
// is compiled into the binary, and so is QuickJS. Every one of those licenses
// requires its copyright notice to travel with the distribution, so this file is
// an obligation rather than a courtesy.
//
// Generated from what esbuild actually pulled into dist/bundle.js, so a package
// that stops being reachable stops being listed, and a new transitive dependency
// cannot slip in unlisted. Re-run it after `npm run build` when dependencies
// change.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bundlePath = path.join(root, 'js', 'dist', 'bundle.js');

if (!fs.existsSync(bundlePath)) {
    console.error('js/dist/bundle.js missing — run `npm run build` in js/ first');
    process.exit(1);
}

const bundle = fs.readFileSync(bundlePath, 'utf8');
const names = new Set();
for (const match of bundle.matchAll(/node_modules[/\\]((?:@[^/\\]+[/\\])?[^/\\\s"'`,)]+)/g)) {
    names.add(match[1].replace(/\\/g, '/'));
}

const packages = [];
for (const name of [...names].sort()) {
    let meta;
    try {
        meta = JSON.parse(fs.readFileSync(path.join(root, 'js', 'node_modules', name, 'package.json'), 'utf8'));
    } catch {
        continue; // a path fragment that is not a package root
    }

    let repository = meta.repository;
    if (repository && typeof repository === 'object') {
        repository = repository.url;
    }
    repository = (repository || '')
        .replace(/^git\+/, '')
        .replace(/\.git$/, '')
        .replace(/^git:\/\//, 'https://')
        .replace(/^ssh:\/\/git@/, 'https://');

    packages.push({ name: meta.name, version: meta.version, license: meta.license ?? 'see package', repository });
}

// The submodule's checked-out tag, so the notice names the version actually built.
const quickjs = (() => {
    try {
        const status = execFileSync('git', ['submodule', 'status', 'third_party/quickjs'],
                                    { cwd: root, encoding: 'utf8' });
        const tag = /\(([^)]+)\)/.exec(status);
        return tag ? tag[1] : status.trim().split(/\s+/)[0].slice(0, 10);
    } catch {
        return 'vendored submodule';
    }
})();

const rows = packages.map((p) => `| [${p.name}](${p.repository}) | ${p.version} | ${p.license} |`).join('\n');

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), `# Third-party notices

GENERATED by \`scripts/generate-notices.mjs\` — do not edit.

The built library **contains** the code below: the JS bundle is compiled into
\`twk.dll\` (and its siblings), and so is the QuickJS engine. Anyone redistributing
that binary redistributes these works, and their licenses require the copyright
notices to travel with it. Full license texts are in each project's repository
and, for the JS packages, in \`js/node_modules/<name>\`.

ton-walletkit-core itself is MIT-licensed; see [LICENSE](LICENSE).

## Engine

| project | version | license |
|---|---|---|
| [QuickJS-ng](https://github.com/quickjs-ng/quickjs) | ${quickjs} | MIT |

Copyright (c) 2017-2026 Fabrice Bellard, 2017-2024 Charlie Gordon,
2023-2026 Ben Noordhuis and QuickJS-ng contributors.

## JavaScript embedded in the bundle

Everything esbuild pulled into \`js/dist/bundle.js\` (${packages.length} packages):

| package | version | license |
|---|---|---|
${rows}

## Platform libraries (linked, not embedded)

BCrypt (Windows), CommonCrypto (Apple) and libcurl or OpenSSL where configured
are used through their system or package-manager copies and are not redistributed
by this project.
`);

console.log(`THIRD_PARTY_NOTICES.md: ${packages.length} JS packages + QuickJS`);
