// The license header every file in this repository carries, and the logic that
// puts it there. Same shape as Unigram's, with this project's license.
//
// Shared with the code generators rather than only living in add-headers.mjs:
// regenerated output has to come out byte-identical to what is checked in, and
// CI enforces that with `git diff --exit-code` on the generated facade.

export const COPYRIGHT = 'Copyright (c) Fela Ameghino 2026';
export const LICENSE = [
    'Distributed under the MIT License. (See accompanying file LICENSE or copy at',
    'https://opensource.org/licenses/MIT)',
];

// Extension -> line comment marker. Anything not listed is left alone: JSON has
// no comments, Markdown headers belong in the prose, and vendored code is not
// ours to label.
const MARKERS = {
    '.c': '//',
    '.cpp': '//',
    '.h': '//',
    '.hpp': '//',
    '.cs': '//',
    '.java': '//',
    '.js': '//',
    '.mjs': '//',
    '.ts': '//',
    '.mts': '//',
    '.cmake': '#',
    '.ps1': '#',
    '.sh': '#',
    '.yml': '#',
    '.bat': '::',
    '.cmd': '::',
};

const BY_NAME = {
    'CMakeLists.txt': '#',
};

/** The comment marker for a path, or null if it should not get a header. */
export function markerFor(file) {
    const name = file.replace(/\\/g, '/').split('/').pop();
    if (BY_NAME[name] !== undefined) {
        return BY_NAME[name];
    }
    const dot = name.lastIndexOf('.');
    return dot < 0 ? null : (MARKERS[name.slice(dot).toLowerCase()] ?? null);
}

/**
 * The header block, without a trailing newline. It both opens and closes with a
 * bare marker line, so a file's own comment block can continue straight from it.
 */
export function headerFor(marker) {
    return [marker, `${marker} ${COPYRIGHT}`, marker, ...LICENSE.map((line) => `${marker} ${line}`), marker]
        .join('\n');
}

export function hasHeader(source) {
    return source.includes(COPYRIGHT);
}

/**
 * Whether a file is generated output. Those get no header: the license at the
 * root covers them, and a header on a file nobody edits is noise that every
 * regeneration has to reproduce exactly. Detected by content rather than by
 * path, because the generated Java facade sits in the same directory as the
 * hand-written classes it completes.
 */
export function looksGenerated(source) {
    const top = source.split('\n', 20).join('\n');
    return /GENERATED by|<auto-generated>|generated by Openapi Generator/i.test(top);
}

/**
 * `source` with the header added, or unchanged if it already has one (so this is
 * safe to re-run) or the file type takes no header.
 */
export function withHeader(source, file) {
    const marker = markerFor(file);
    if (marker === null || hasHeader(source)) {
        return source;
    }

    const lines = source.split('\n');
    let at = 0;
    // Three things have to stay at the top: a shebang; C#'s <auto-generated>
    // marker, which is what tells analyzers and formatters to skip the file; and
    // a batch file's `@echo off`, since anything above it gets echoed to the
    // console on every run.
    const skip = (line) =>
        line.startsWith('#!') ||
        line.trim() === '// <auto-generated>' ||
        line.trim().toLowerCase() === '@echo off';
    while (at < lines.length && skip(lines[at])) {
        at++;
    }

    const block = headerFor(marker).split('\n');
    const next = lines[at] ?? '';
    if (next.trim() === marker) {
        // The file opens its own comment block with a bare marker line. Drop it
        // and let the description continue the header's block instead of
        // starting a second one right below it.
        lines.splice(at, 1);
    } else if (!next.startsWith(marker)) {
        // Code, not a comment: keep the header visually separate from it.
        block.push('');
    }

    lines.splice(at, 0, ...block);
    return lines.join('\n');
}
